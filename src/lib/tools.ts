export const getCategory = (slug: CategorySlug): Category => {
  const found = categories.find((c) => c.slug === slug);
  if (!found) {
    throw new Error(`Unknown category slug: ${slug}`);
  }
  return found;
};

export const getAllTools = (): Tool[] => categories.flatMap((c) => c.tools);

export const getToolBySlug = (slug: string): Tool | undefined =>
  getAllTools().find((t) => t.slug === slug);

export const searchTools = (
  query: string,
  categoryFilter: CategorySlug | "all" = "all",
): Tool[] => {
  const normalized = query.trim().toLowerCase();
  const pool =
    categoryFilter === "all"
      ? getAllTools()
      : (categories.find((c) => c.slug === categoryFilter)?.tools ?? []);

  if (!normalized) {
    return pool;
  }

  const terms = normalized.split(/\s+/).filter(Boolean);

  return pool.filter((tool) => {
    const haystack = [
      tool.name,
      tool.desc,
      tool.categoryLabel,
      tool.subcategory ?? "",
      tool.slug,
      ...tool.keywords,
    ]
      .join(" ")
      .toLowerCase();

    return terms.every((term) => haystack.includes(term));
  });
};
